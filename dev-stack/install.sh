#!/usr/bin/env bash
# Installs FacturaScripts locally: image, database, composer dependencies and the
# unattended installer. Idempotent — safe to re-run; it never overwrites an
# existing dev-stack/.env or an existing config.php.
#
# Usage: dev-stack/install.sh
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(dirname "$HERE")"
ENV_FILE="$HERE/.env"
BUILDER=facturascripts-builder
PORT_HOST=8180

cd "$ROOT"

# ---------------------------------------------------------------- secrets
if [ ! -f "$ENV_FILE" ]; then
    umask 077
    cat > "$ENV_FILE" <<EOF
# Generated by dev-stack/install.sh — NOT committed (see .gitignore).
FS_DB_PASS=$(openssl rand -base64 24 | tr -d '/+=' | cut -c1-24)
MARIADB_ROOT_PASSWORD=$(openssl rand -base64 24 | tr -d '/+=' | cut -c1-24)
FS_INITIAL_USER=admin
FS_INITIAL_PASS=$(openssl rand -base64 24 | tr -d '/+=' | cut -c1-24)
FS_LANG=fr_FR
FS_BIND_ADDR=$(tailscale ip -4 2>/dev/null | head -1 || echo 127.0.0.1)
EOF
    echo "✓ $ENV_FILE generated"
else
    echo "✓ $ENV_FILE exists, kept as is"
fi

# Everything below talks to the app through the address it is actually bound to.
set -a; . "$ENV_FILE"; set +a
BASE_URL="http://${FS_BIND_ADDR:-127.0.0.1}:${PORT_HOST}"

# ---------------------------------------------------------------- image
# Tailscale hijacks DNS inside build containers: build with host networking so
# apt/composer resolve. `--dns` is not supported by buildx.
if ! docker buildx inspect "$BUILDER" >/dev/null 2>&1; then
    docker buildx create --name "$BUILDER" --driver docker-container --driver-opt network=host >/dev/null
fi
docker buildx build --builder "$BUILDER" --load -t facturascripts-app:8.3 "$HERE" >/dev/null
echo "✓ image facturascripts-app:8.3"

# ---------------------------------------------------------------- database
docker compose -f "$HERE/docker-compose.yml" --env-file "$ENV_FILE" up -d db
for _ in $(seq 1 60); do
    if docker exec facturascripts-db healthcheck.sh --connect --innodb_initialized >/dev/null 2>&1; then
        echo "✓ database ready"
        break
    fi
    sleep 1
done

# ---------------------------------------------------------------- dependencies
# Run as the host user so the bind mount stays owned by us, not root.
if [ ! -d "$ROOT/vendor" ]; then
    docker compose -f "$HERE/docker-compose.yml" --env-file "$ENV_FILE" run --rm \
        -u "$(id -u):$(id -g)" -e HOME=/tmp -e COMPOSER_HOME=/tmp/composer \
        --entrypoint composer app install --no-interaction --no-progress
    echo "✓ composer dependencies installed"
else
    echo "✓ vendor/ present, skipped composer install"
fi

# ---------------------------------------------------------------- app
docker compose -f "$HERE/docker-compose.yml" --env-file "$ENV_FILE" up -d app
for _ in $(seq 1 60); do
    if curl -fsS -o /dev/null "$BASE_URL/" 2>/dev/null; then break; fi
    sleep 1
done
echo "✓ app responding on $BASE_URL"

# ---------------------------------------------------------------- installer
if [ -f "$ROOT/config.php" ]; then
    echo "✓ config.php present, application already installed"
else
    set -a; . "$ENV_FILE"; set +a
    response="$(curl -fsS -X POST "$BASE_URL/" \
        --data-urlencode "fs_db_type=mysql" \
        --data-urlencode "fs_db_host=db" \
        --data-urlencode "fs_db_port=3306" \
        --data-urlencode "fs_db_name=facturascripts" \
        --data-urlencode "fs_db_user=facturascripts" \
        --data-urlencode "fs_db_pass=${FS_DB_PASS}" \
        --data-urlencode "fs_initial_user=${FS_INITIAL_USER}" \
        --data-urlencode "fs_initial_pass=${FS_INITIAL_PASS}" \
        --data-urlencode "fs_route=" \
        --data-urlencode "fs_lang=${FS_LANG:-fr_FR}" \
        --data-urlencode "unattended=1")"
    if [ "$response" = "OK" ]; then
        echo "✓ installer finished (config.php written)"
    else
        echo "✗ installer did not report OK; first 400 chars of the page follow:" >&2
        printf '%s\n' "$response" | head -c 400 >&2
        exit 1
    fi
fi

# The initial admin credentials are handed to the owner this way, once.
echo
echo "URL:      $BASE_URL   (and http://self0.tail7e037e.ts.net:${PORT_HOST})"
echo "Login:    ${FS_INITIAL_USER:-admin} / see $ENV_FILE for the generated password"
